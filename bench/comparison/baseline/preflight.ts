import { resolve } from "node:path"
import { QUALIFICATION_ARTIFACT } from "../../../scripts/native-storage-qualification/artifact"
import { protocolDigest } from "../prepare"

const root=resolve(import.meta.dir,"../../.."), output=resolve(root,".wrangler/comparison-preflight")
const oracle=await Bun.build({entrypoints:[resolve(import.meta.dir,"../oracle.ts")],target:"bun",minify:false})
if(!oracle.success || oracle.outputs.length!==1)throw new Error("trusted oracle bundling failed")
await Bun.write(resolve(output,"oracle-source.ts"),`export const TRUSTED_ORACLE = ${JSON.stringify(await oracle.outputs[0]!.text())}\n`)
const config=JSON.parse((await Bun.file(resolve(import.meta.dir,"wrangler.template.jsonc")).text()))
config.name="aboiteau-r0-23-offline-preflight"
config.account_id="00000000000000000000000000000000"
config.main=resolve(import.meta.dir,"worker.ts")
config.$schema=resolve(root,"node_modules/wrangler/config-schema.json")
// Offline-only stubs generate binding types; live credentials must be Worker secrets.
config.vars={...config.vars,BENCH_TOKEN:"offline-synthetic-token-not-a-live-credential",API_TOKEN:"offline-synthetic-token-not-a-live-credential",VAULT_MASTER_KEY:"0".repeat(64),BENCH_PROVIDER_KEY:"",BENCH_PROVIDER_ORG:""}
config.r2_buckets[0].bucket_name="r0-23-offline-preflight-not-live"
for(const container of config.containers)container.images.evented.image=QUALIFICATION_ARTIFACT.image
await Bun.write(resolve(import.meta.dir,"freeze.generated.ts"),`// Generated by preflight.ts. This derivative is excluded from its own digest.\nexport const FROZEN_PROTOCOL_SHA256 = ${JSON.stringify(protocolDigest())}\n`)
const path=resolve(output,"wrangler.json")
await Bun.write(path,JSON.stringify(config,null,2)+"\n")
for(const args of [
  ["types",resolve(import.meta.dir,"bindings.generated.d.ts"),"--config",path,"--env-interface","ComparisonBindings","--include-runtime=false"],
  ["deploy","--config",path,"--dry-run","--outdir",resolve(output,"bundle")],
]) {
  const child=Bun.spawn([resolve(root,"node_modules/.bin/wrangler"),...args],{cwd:root,stdout:"inherit",stderr:"inherit",env:{...process.env,WRANGLER_SEND_METRICS:"false",WRANGLER_LOG_PATH:resolve(output,"wrangler.log")}})
  if(await child.exited!==0)throw new Error("offline baseline preflight failed")
}
console.log("Comparison baseline bundled offline with pinned image. No resources created; native Linux and real-model equivalence remain unmeasured.")
