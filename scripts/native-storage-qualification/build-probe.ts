import { mkdirSync, renameSync, rmSync } from "node:fs"
import { resolve } from "node:path"

/** Bundle typed probe modules for the image's Bun, then embed only their source. */
const output = resolve(import.meta.dir, "../../.wrangler/native-storage-preflight")
mkdirSync(output, { recursive: true })
const built = await Bun.build({ entrypoints: [resolve(import.meta.dir, "matrix-probe.ts")], target: "bun", minify: false })
if (!built.success) throw new AggregateError(built.logs, "fixed probe bundle failed")
const source = await built.outputs[0].text()
const module = `// Generated by build-probe.ts; do not edit.\nexport const NATIVE_STORAGE_PROBE = ${JSON.stringify(source)}\n`
for (const [name, content] of [["probe.js", source], ["probe-source.ts", module]]) {
  const target = resolve(output, name)
  if (!(await Bun.file(target).exists()) || await Bun.file(target).text() !== content) {
    const temporary = `${target}.${crypto.randomUUID()}.tmp`
    try { await Bun.write(temporary, content); renameSync(temporary, target) }
    finally { rmSync(temporary, { force: true }) }
  }
}
