const BLOCK = 512

/** Freshness requires that neither startup nor a prior verify attempt occurred. */
export function isFreshStoppedRuntime(input: { running: boolean; hasControlToken: boolean; verificationAttempted?: boolean }): boolean {
  return !input.running && !input.hasControlToken && input.verificationAttempted !== true
}

function text(bytes: Uint8Array): string {
  return new TextDecoder().decode(bytes).replace(/\0.*$/, "")
}

function octal(bytes: Uint8Array): number | undefined {
  const value = text(bytes).trim()
  if (!value) return 0
  if (!/^[0-7]+$/.test(value)) return undefined
  const parsed = Number.parseInt(value, 8)
  return Number.isSafeInteger(parsed) ? parsed : undefined
}

function validChecksum(header: Uint8Array): boolean {
  const expected = octal(header.subarray(148, 156))
  if (expected === undefined) return false
  let actual = 0
  for (let index = 0; index < BLOCK; index++) actual += index >= 148 && index < 156 ? 32 : header[index]!
  return actual === expected
}

/** Inspect GNU tar member names and fail closed on truncation or unknown extensions. */
export function accountArchiveBoundary(bytes: Uint8Array): boolean {
  let offset = 0
  let longName: string | undefined
  let terminated = false
  const names: string[] = []
  while (offset + BLOCK <= bytes.length) {
    const header = bytes.subarray(offset, offset + BLOCK)
    if (header.every((byte) => byte === 0)) {
      if (offset + BLOCK * 2 > bytes.length || !bytes.subarray(offset + BLOCK, offset + BLOCK * 2).every((byte) => byte === 0)) return false
      if (!bytes.subarray(offset + BLOCK * 2).every((byte) => byte === 0)) return false
      terminated = true
      break
    }
    if (!validChecksum(header)) return false
    const size = octal(header.subarray(124, 136))
    if (size === undefined) return false
    const contentOffset = offset + BLOCK
    const next = contentOffset + Math.ceil(size / BLOCK) * BLOCK
    if (next > bytes.length) return false
    const type = header[156] === 0 ? "0" : String.fromCharCode(header[156]!)
    if (type === "L") {
      if (size === 0 || size > 4096) return false
      longName = text(bytes.subarray(contentOffset, contentOffset + size))
    } else if (type === "0" || type === "5") {
      const raw = longName ?? [text(header.subarray(345, 500)), text(header.subarray(0, 100))].filter(Boolean).join("/")
      longName = undefined
      names.push(raw.replace(/^(?:\.\/)+/, "").replace(/\/$/, ""))
    } else {
      // Account state archives are generated by GNU tar. Reject links, PAX and
      // other extensions instead of silently missing their effective names.
      return false
    }
    offset = next
  }
  if (!terminated || longName !== undefined || names.length === 0) return false
  return !names.some((name) => name === "stow" || name.startsWith("stow/") || name === "initialized" ||
    name === "run/stow-ready.json" || name.endsWith("/stow-ready.json"))
}
