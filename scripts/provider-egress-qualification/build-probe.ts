import { mkdirSync, renameSync, rmSync } from "node:fs"
import { resolve } from "node:path"

/** Compile the fixed native probe for the pinned image's Bun runtime. */
const output = resolve(import.meta.dir, "../../.wrangler/provider-egress-preflight")
mkdirSync(output, { recursive: true })
const built = await Bun.build({
  entrypoints: [resolve(import.meta.dir, "container-probe.ts")],
  target: "bun",
  minify: false,
})
if (!built.success || built.outputs.length !== 1) throw new AggregateError(built.logs, "provider egress probe bundle failed")
const source = await built.outputs[0]!.text()
const generated = `// Generated by build-probe.ts; do not edit.\nexport const PROVIDER_EGRESS_PROBE = ${JSON.stringify(source)}\n`
for (const [name, contents] of [["probe.js", source], ["probe-source.ts", generated]] as const) {
  const target = resolve(output, name)
  if (!(await Bun.file(target).exists()) || await Bun.file(target).text() !== contents) {
    const temporary = `${target}.${crypto.randomUUID()}.tmp`
    try {
      await Bun.write(temporary, contents)
      renameSync(temporary, target)
    } finally {
      rmSync(temporary, { force: true })
    }
  }
}
const bindings = `// Generated by build-probe.ts; Wrangler preflight validates the same module exports.\ndeclare namespace Cloudflare {\n  interface GlobalProps {\n    mainModule: typeof import("../../scripts/provider-egress-qualification/worker")\n    durableNamespaces: "ProviderEgressQualification"\n  }\n}\n`
const bindingsPath = resolve(output, "provider-egress-mainmodule.d.ts")
if (!(await Bun.file(bindingsPath).exists()) || await Bun.file(bindingsPath).text() !== bindings) {
  const temporary = `${bindingsPath}.${crypto.randomUUID()}.tmp`
  try {
    await Bun.write(temporary, bindings)
    renameSync(temporary, bindingsPath)
  } finally {
    rmSync(temporary, { force: true })
  }
}
